// Smart Attachment System — helpers for the centralized File Library.
//
// Files live in Supabase Storage bucket "project-documents" under paths of
// the form `{project_id}/{yyyymmdd}_{uuid}_{safeName}` so RLS on
// storage.objects can look the project up by the first path segment.
//
// Metadata rows live in `project_files`, linked to a folder in
// `project_folders`. Every contextual upload auto-routes into a canonical
// folder pathway derived from the source entity (e.g. Crew → "Crew Profiles
// → {name}").
import { storageAudited } from "@/lib/storage-audit";
import { assertUploadAllowed, uploadContentType } from "@/lib/upload-policy";
import { supabase } from "@/integrations/supabase/client";

export const BUCKET = "project-documents";

export type EntityType =
  "crew" | "cast" | "invoice" | "vendor" | "payroll" | "purchase_order" | "other";

/** Canonical parent folder for each entity type (auto-generated on demand). */
export const ENTITY_ROOT: Record<EntityType, string> = {
  crew: "Crew Profiles",
  cast: "Cast Profiles",
  invoice: "Invoices",
  vendor: "Vendors",
  payroll: "Payroll",
  purchase_order: "Purchase Orders",
  other: "Uncategorized",
};

export type FolderRow = {
  id: string;
  project_id: string;
  organization_id: string | null;
  parent_id: string | null;
  name: string;
  auto_generated: boolean;
  created_at: string;
  updated_at: string;
};

export type FileRow = {
  id: string;
  project_id: string;
  organization_id: string | null;
  folder_id: string | null;
  name: string;
  /** Filename as chosen by the uploader. Null for files uploaded before this field existed. */
  original_file_name?: string | null;
  storage_path: string;
  file_url: string | null;
  mime_type: string | null;
  size_bytes: number | null;
  entity_type: string | null;
  entity_id: string | null;
  uploaded_by: string | null;
  created_at: string;
  updated_at: string;
};

async function getProjectOrg(projectId: string): Promise<string | null> {
  const { data } = await supabase
    .from("projects")
    .select("organization_id")
    .eq("id", projectId)
    .maybeSingle();
  return (data?.organization_id as string | null) ?? null;
}

/** Find or create a folder with the given name under a given parent. */
export async function ensureFolder(
  projectId: string,
  name: string,
  parentId: string | null,
  opts: { autoGenerated?: boolean } = {},
): Promise<FolderRow> {
  const trimmed = name.trim();
  if (!trimmed) throw new Error("Folder name is required");

  const q = supabase
    .from("project_folders")
    .select("*")
    .eq("project_id", projectId)
    .ilike("name", trimmed);
  const { data: existing, error: readErr } = parentId
    ? await q.eq("parent_id", parentId)
    : await q.is("parent_id", null);
  if (readErr) throw readErr;
  if (existing && existing.length) return existing[0] as FolderRow;

  const organization_id = await getProjectOrg(projectId);
  const { data, error } = await supabase
    .from("project_folders")
    .insert({
      project_id: projectId,
      organization_id,
      parent_id: parentId,
      name: trimmed,
      auto_generated: !!opts.autoGenerated,
    })
    .select("*")
    .single();
  if (error) throw error;
  return data as FolderRow;
}

/** Build/find the canonical folder pathway for a given entity. */
export async function ensureEntityFolder(
  projectId: string,
  entityType: EntityType,
  entityLabel: string,
): Promise<FolderRow> {
  const root = await ensureFolder(projectId, ENTITY_ROOT[entityType], null, {
    autoGenerated: true,
  });
  const label = (entityLabel || "Unnamed").trim().slice(0, 120);
  return ensureFolder(projectId, label, root.id, { autoGenerated: true });
}

/**
 * Extract a safe ASCII extension (Storage rejects non-ASCII path segments).
 * The original filename is preserved separately in the `name` column so
 * the UI can still display Arabic/other scripts.
 */
function extractSafeExtension(name: string): string {
  const dot = name.lastIndexOf(".");
  if (dot === -1 || dot === name.length - 1) return "";
  const ext = name
    .slice(dot + 1)
    .replace(/[^A-Za-z0-9]/g, "")
    .slice(0, 10);
  return ext ? `.${ext.toLowerCase()}` : "";
}

/** Upload a file, ensure the auto-routed folder exists, insert metadata. */
export async function uploadProjectFile(params: {
  projectId: string;
  file: File;
  entityType?: EntityType;
  entityId?: string | null;
  entityLabel?: string;
  folderId?: string | null;
}): Promise<FileRow> {
  const { projectId, file } = params;
  if (!projectId) throw new Error("An active project is required.");

  let folderId: string | null = params.folderId ?? null;
  if (!folderId && params.entityType) {
    const f = await ensureEntityFolder(
      projectId,
      params.entityType,
      params.entityLabel ?? "Unnamed",
    );
    folderId = f.id;
  }

  // Storage keys must be ASCII. Use a UUID-based path so filenames with
  // Arabic/CJK characters or spaces don't produce "Invalid key" errors.
  assertUploadAllowed(file);
  const ext = extractSafeExtension(file.name);
  const storagePath = `${projectId}/${crypto.randomUUID()}${ext}`;

  const { error: upErr } = await storageAudited.from(BUCKET).upload(storagePath, file, {
    upsert: false,
    contentType: uploadContentType(file),
  });
  if (upErr) throw upErr;

  const organization_id = await getProjectOrg(projectId);
  const { data: userData } = await supabase.auth.getUser();
  const { data, error } = await supabase
    .from("project_files")
    .insert({
      project_id: projectId,
      organization_id,
      folder_id: folderId,
      name: file.name,
      original_file_name: file.name,
      storage_path: storagePath,
      mime_type: file.type || null,
      size_bytes: file.size ?? null,
      entity_type: params.entityType ?? null,
      entity_id: params.entityId ?? null,
      uploaded_by: userData?.user?.id ?? null,
    })
    .select("*")
    .single();
  if (error) {
    // Best-effort cleanup if metadata insert fails.
    await storageAudited.from(BUCKET).remove([storagePath]);
    throw error;
  }
  return data as FileRow;
}

/** Signed URL for previewing/downloading a stored file. */
export async function getSignedUrl(path: string, ttlSeconds = 60 * 30) {
  const { data, error } = await storageAudited.from(BUCKET).createSignedUrl(path, ttlSeconds);
  if (error) throw error;
  return data.signedUrl;
}

export async function deleteProjectFile(file: FileRow) {
  await storageAudited.from(BUCKET).remove([file.storage_path]);
  const { error } = await supabase.from("project_files").delete().eq("id", file.id);
  if (error) throw error;
}

/** Rename a file's display name (storage key is immutable). */
export async function renameProjectFile(id: string, newName: string): Promise<FileRow> {
  const trimmed = newName.trim();
  if (!trimmed) throw new Error("File name is required");
  const { data, error } = await supabase
    .from("project_files")
    .update({ name: trimmed })
    .eq("id", id)
    .select("*")
    .single();
  if (error) throw error;
  return data as FileRow;
}

/** Download a file as a Blob (for zipping or client-side saves). */
export async function downloadFileBlob(path: string): Promise<Blob> {
  const { data, error } = await storageAudited.from(BUCKET).download(path);
  if (error) throw error;
  return data;
}

export async function listFilesForEntity(
  projectId: string,
  entityType: EntityType,
  entityId: string,
): Promise<FileRow[]> {
  const { data, error } = await supabase
    .from("project_files")
    .select("*")
    .eq("project_id", projectId)
    .eq("entity_type", entityType)
    .eq("entity_id", entityId)
    .order("created_at", { ascending: false });
  if (error) throw error;
  return (data ?? []) as FileRow[];
}

export async function listFolders(projectId: string): Promise<FolderRow[]> {
  const { data, error } = await supabase
    .from("project_folders")
    .select("*")
    .eq("project_id", projectId)
    .order("name", { ascending: true });
  if (error) throw error;
  return (data ?? []) as FolderRow[];
}

export async function listFilesInFolder(
  projectId: string,
  folderId: string | null,
): Promise<FileRow[]> {
  let q = supabase.from("project_files").select("*").eq("project_id", projectId);
  q = folderId ? q.eq("folder_id", folderId) : q.is("folder_id", null);
  const { data, error } = await q.order("created_at", { ascending: false });
  if (error) throw error;
  return (data ?? []) as FileRow[];
}

/**
 * Human-readable name for a stored file.
 * Falls back gracefully for legacy rows uploaded before `original_file_name`
 * existed: display `name`, then the last storage-path segment, then a literal.
 */
export function getDisplayName(
  file: Partial<Pick<FileRow, "original_file_name" | "name" | "storage_path">> | null | undefined,
): string {
  if (!file) return "Unnamed file";
  const original = (file.original_file_name ?? "").trim();
  if (original) return original;
  const name = (file.name ?? "").trim();
  if (name) return name;
  const path = (file.storage_path ?? "").trim();
  if (path) {
    const seg = path.split("/").filter(Boolean).pop();
    if (seg) return seg;
  }
  return "Unnamed file";
}

/**
 * Cascade cleanup: remove every managed attachment linked to a parent entity
 * from Storage first, then from `project_files`.
 *
 * Returns `false` when the attachment lookup itself fails, so callers can abort
 * the parent deletion instead of orphaning files with no way to find them.
 */
export async function deleteFilesForEntity(
  projectId: string,
  entityType: EntityType,
  entityId: string,
): Promise<boolean> {
  const { data, error } = await supabase
    .from("project_files")
    .select("id, storage_path")
    .eq("project_id", projectId)
    .eq("entity_type", entityType)
    .eq("entity_id", entityId);
  if (error) {
    console.error("Failed to fetch attachments for cleanup:", error);
    return false;
  }
  const rows = data ?? [];
  if (!rows.length) return true;

  const paths = rows.map((r) => r.storage_path).filter(Boolean) as string[];
  if (paths.length) {
    // Storage failures are logged but never block the parent deletion.
    const { error: storageError } = await storageAudited.from(BUCKET).remove(paths);
    if (storageError) console.error("Storage cleanup failed:", storageError);
  }

  const { error: dbError } = await supabase
    .from("project_files")
    .delete()
    .in(
      "id",
      rows.map((r) => r.id),
    );
  if (dbError) console.error("Attachment record cleanup failed:", dbError);
  return true;
}
