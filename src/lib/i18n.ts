/**
 * Strict language resolution: English is the default for everyone.
 * Arabic is used ONLY when the user explicitly toggled it (persisted flag).
 * No navigator/browser detection is consulted.
 */
function resolveInitialLang(): "en" | "ar" {
  if (typeof document === "undefined") return "en";
  let saved: string | null = null;
  try {
    saved = localStorage.getItem("kwalis.lang");
  } catch {}
  if (!saved) {
    const m = document.cookie.match(/(?:^|;\s*)kwalis\.lang=(en|ar)/);
    saved = m?.[1] ?? null;
  }
  return saved === "ar" ? "ar" : "en";
}

const initialLang = resolveInitialLang();

if (!i18n.isInitialized) {
  i18n.use(initReactI18next).init({
    resources: {
      en: { translation: deepMerge(en as unknown as Dict, enDict as Dict) },
      ar: { translation: deepMerge(ar as unknown as Dict, arDict as Dict) },
    },
    lng: initialLang,
    fallbackLng: "en",
    supportedLngs: ["en", "ar"],
    interpolation: { escapeValue: false },
    detection: undefined,
    react: { useSuspense: false },
  });
}

function applyDir(lng: string) {
  if (typeof document === "undefined") return;
  const dir = lng === "ar" ? "rtl" : "ltr";
  document.documentElement.setAttribute("dir", dir);
  document.documentElement.setAttribute("lang", lng);
  try {
    localStorage.setItem("kwalis.lang", lng);
    localStorage.setItem("kwalis.dir", dir);
  } catch {}
  persistCookie(lng);
}

/**
 * Mirror the language into a 1-year cookie so the preference survives
 * localStorage clears and is available to the server on the very first
 * render (no flash of the wrong direction).
 */
function persistCookie(lng: string) {
  if (typeof document === "undefined") return;
  try {
    document.cookie = `kwalis.lang=${lng};path=/;max-age=${60 * 60 * 24 * 365};samesite=lax`;
  } catch {}
}

if (typeof document !== "undefined") {
  // Prefer persisted preference so refresh preserves the user's language + direction
  // before i18next's detector fully wires up.
  if (i18n.language !== initialLang) void i18n.changeLanguage(initialLang);
  applyDir(initialLang);
  i18n.on("languageChanged", applyDir);
}

export function setLanguage(lng: "en" | "ar") {
  try {
    localStorage.setItem("kwalis.lang", lng);
  } catch {}
  persistCookie(lng);
  void i18n.changeLanguage(lng);
}

