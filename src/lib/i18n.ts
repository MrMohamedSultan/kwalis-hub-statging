type Dict = Record<string, unknown>;

/** Deep merge where `override` wins; the shared cinematic dictionaries are layered ON TOP of the legacy inline ones. */
function deepMerge(base: Dict, override: Dict): Dict {
  const out: Dict = { ...base };
  for (const [key, value] of Object.entries(override)) {
    const prev = out[key];
    if (prev && typeof prev === "object" && value && typeof value === "object") {
      out[key] = deepMerge(prev as Dict, value as Dict);
    } else {
      out[key] = value;
    }
  }
  return out;
}

