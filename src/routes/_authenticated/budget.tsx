// --- Header overrides (inline rename / re-code) persisted to localStorage ---
type HeaderOverride = { code?: string; name?: string };
type HeaderOverrideMap = Record<string, HeaderOverride>;
// v2: bumped after chart-of-accounts seed reorg (added 1000 Development Costs,
// renamed BTL headers 2000-3900). Old v1 overrides are ignored so the fresh
// ATL/BTL structure appears immediately on the Budget Creation page.
const HEADER_OVERRIDE_KEY = "budget.headerOverrides.v3";

function useHeaderOverrides() {
  const [overrides, setOverrides] = useState<HeaderOverrideMap>(() => {
    if (typeof window === "undefined") return {};
    try {
      return JSON.parse(localStorage.getItem(HEADER_OVERRIDE_KEY) ?? "{}");
    } catch {
      return {};
    }
  });
  useEffect(() => {
    try {
      localStorage.setItem(HEADER_OVERRIDE_KEY, JSON.stringify(overrides));
    } catch {}
  }, [overrides]);
  const effective = useMemo(
    () =>
      HEADER_ACCOUNTS.map((h) => ({
        ...h,
        code: overrides[h.code]?.code ?? h.code,
        name: overrides[h.code]?.name ?? h.name,
        _originalCode: h.code,
      })),
    [overrides],
  );
  const setOverride = (originalCode: string, patch: HeaderOverride) =>
    setOverrides((o) => ({ ...o, [originalCode]: { ...o[originalCode], ...patch } }));
  return { overrides, effective, setOverride };
}

function SearchableHeaderSelect({
  value,
  onChange,
  headers,
}: {
  value: string;
  onChange: (code: string) => void;
  headers: { code: string; name: string; group: MacroCategory }[];
}) {
  const listId = useMemo(() => `hdrs-${Math.random().toString(36).slice(2, 9)}`, []);
  const current = headers.find((h) => h.code === value);
  const [text, setText] = useState(current ? `${current.code} — ${current.name}` : value);
  useEffect(() => {
    const c = headers.find((h) => h.code === value);
    setText(c ? `${c.code} — ${c.name}` : value);
  }, [value, headers]);
  const commit = (v: string) => {
    const m = headers.find(
      (h) => v === `${h.code} — ${h.name}` || v === h.code || v.startsWith(h.code + " "),
    );
    if (m) onChange(m.code);
  };
  return (
    <>
      <input
        list={listId}
        value={text}
        onChange={(e) => {
          setText(e.target.value);
          commit(e.target.value);
        }}
        placeholder={headers.length ? "Search header account…" : "No headers in this category"}
        className="bg-sidebar-active text-white border border-border rounded-lg px-3 py-2 w-full outline-none"
      />
      <datalist id={listId}>
        {headers.map((h) => (
          <option key={h.code} value={`${h.code} — ${h.name}`}>
            {h.group}
          </option>
        ))}
      </datalist>
    </>
  );
}

