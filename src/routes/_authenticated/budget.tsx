function useTopsheetAccounts() {
  const [accounts, setAccounts] = useState<TopsheetAccount[]>([]);
  const [loading, setLoading] = useState(true);
  useEffect(() => {
    let cancel = false;
    (async () => {
      const { data, error } = await supabase
        .from("budget_topsheet_accounts" as any)
        .select("*")
        .order("display_order", { ascending: true });
      if (cancel) return;
      if (error) toast.error(i18n.t("budget.failed_to_load_top_sheet_codes") + error.message);
      else setAccounts((data ?? []) as unknown as TopsheetAccount[]);
      setLoading(false);
    })();
    return () => {
      cancel = true;
    };
  }, []);
  return { accounts, loading };
}

