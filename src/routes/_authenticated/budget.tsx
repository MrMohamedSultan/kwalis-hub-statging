                                const text = e.clipboardData.getData("text");
                                if (!text || (!text.includes("\t") && !text.includes("\n"))) return;
                                e.preventDefault();
                                const rows = text
                                  .replace(/\r/g, "")
                                  .replace(/\n+$/, "")
                                  .split("\n")
                                  .map((r) => r.split("\t"));
                                const startIdx = INLINE_FIELDS.indexOf(startField);
