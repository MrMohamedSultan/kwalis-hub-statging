                                      (target.selectionEnd ?? 0) === 0;
                                    const atEnd =
                                      (target.selectionStart ?? 0) === target.value.length &&
                                      (target.selectionEnd ?? 0) === target.value.length;
                                    if (dir === -1 && !atStart) return;
                                    if (dir === 1 && !atEnd) return;
