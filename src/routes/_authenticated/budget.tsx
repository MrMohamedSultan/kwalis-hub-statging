// Auto-derive Top Sheet bucket from a line's mainCode / headerCode.
// Shared by budget creation, the "Add sub-line" modal, and the retroactive
// backfill in the view/edit table. Kept identical to TopSheetPanel.deriveCode
// so on-screen rollups match the persisted topsheetCode value.
export function autoDeriveTopsheetCode(
  mainCode: string | undefined | null,
  headerCode: string | undefined | null,
  accounts: TopsheetAccount[],
): string | null {
  if (!accounts || accounts.length === 0) return null;
  const raw = String(mainCode || headerCode || "")
    .trim()
    .replace(/\.0+$/, "");
  if (!raw) return null;
  const direct = accounts.find((a) => a.code === raw);
  if (direct) return direct.code;
  const num = parseInt(raw, 10);
  if (!Number.isFinite(num)) return null;
  for (const a of accounts) {
    const m = a.code.match(/^(\d+)\s*-\s*(\d+)$/);
    if (m && num >= +m[1] && num <= +m[2]) return a.code;
  }
  const hundred = String(Math.floor(num / 100) * 100);
  const h = accounts.find((a) => a.code === hundred);
  if (h) return h.code;
  let best: TopsheetAccount | null = null;
  for (const a of accounts) {
    const an = parseInt(a.code, 10);
    if (Number.isFinite(an) && an <= num && (!best || an > parseInt(best.code, 10))) best = a;
  }
  return best?.code ?? null;
}

